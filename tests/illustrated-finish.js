// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async (page) => {
  const checks = []
  const check = (value, label) => { if (!value) throw new Error(label); checks.push(label) }
  await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => b.textContent === 'Добавить группу' && !b.disabled) || document.querySelector('[role="alert"]'), null, { timeout: 600000 })
  if (await page.getByRole('alert').count()) throw new Error(await page.getByRole('alert').allTextContents())
  const preview = page.getByLabel('Предпросмотр группы', { exact: true })
  await preview.locator('img').nth(2).waitFor()
  check(await preview.locator('img').count() === 3, 'Three composed previews generated by live provider')
  await preview.screenshot({ path: 'output/playwright/illustrated-preview.png' })
  await page.getByRole('button', { name: 'Добавить группу', exact: true }).click()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  check(await page.getByRole('button', { name: /^Открыть слайд/ }).count() === 3, 'Three illustrated slides inserted')
  const generatedGroup = await page.locator('#group').inputValue()
  for (let i = 0; i < 3; i++) {
    await page.getByRole('button', { name: /^Открыть слайд/ }).nth(i).click()
    check(await page.getByRole('button', { name: 'Иллюстрация', exact: true }).count() === 1, `Slide ${i + 1} has an editable picture layer`)
    await page.getByRole('button', { name: 'Заголовок', exact: true }).click()
    check((await page.getByLabel('Текст слоя', { exact: true }).inputValue()).length > 5, `Slide ${i + 1} has editable heading`)
    check(await page.getByRole('alert').count() === 0, `Slide ${i + 1} text fits`)
  }
  await page.getByRole('button', { name: /^Открыть слайд/ }).first().click()
  await page.getByRole('button', { name: 'Иллюстрация', exact: true }).click()
  const beforeX = Number(await page.getByLabel('X', { exact: true }).inputValue())
  const beforeY = Number(await page.getByLabel('Y', { exact: true }).inputValue())
  const width = Number(await page.getByLabel('Ширина слоя', { exact: true }).inputValue())
  const height = Number(await page.getByLabel('Высота слоя', { exact: true }).inputValue())
  await page.getByRole('region', { name: 'Холст слайда' }).scrollIntoViewIfNeeded()
  const box = await page.locator('.konvajs-content').boundingBox()
  const scale = box.width / 1080
  await page.mouse.move(box.x + (beforeX + width / 2) * scale, box.y + (beforeY + height / 2) * scale)
  await page.mouse.down()
  await page.mouse.move(box.x + (beforeX + width / 2 + 25) * scale, box.y + (beforeY + height / 2 + 10) * scale, { steps: 10 })
  await page.mouse.up()
  check(Number(await page.getByLabel('X', { exact: true }).inputValue()) > beforeX + 15, 'Generated picture can be dragged')
  await page.getByRole('button', { name: 'Отменить изменение', exact: true }).click()
  await page.getByLabel('Ширина слоя', { exact: true }).fill(String(Math.round(width * .8)))
  check(Math.abs(Number(await page.getByLabel('Высота слоя', { exact: true }).inputValue()) / Number(await page.getByLabel('Ширина слоя', { exact: true }).inputValue()) - height / width) < .01, 'Generated picture scales proportionally')
  await page.getByRole('button', { name: 'Отменить изменение', exact: true }).click()
  await page.getByRole('button', { name: 'Удалить слой', exact: true }).click()
  check(await page.getByRole('button', { name: 'Иллюстрация', exact: true }).count() === 0, 'Generated picture can be deleted')
  await page.getByRole('button', { name: 'Отменить изменение', exact: true }).click()
  check(await page.getByRole('button', { name: 'Иллюстрация', exact: true }).count() === 1, 'Undo restores generated picture')
  for (const [button, path] of [['Сохранить JSON', 'illustrated-project.json'], ['PNG', 'illustrated-cover.png'], ['ZIP группы', 'illustrated-group.zip']]) {
    const download = page.waitForEvent('download')
    await page.getByRole('button', { name: button, exact: true }).click()
    await (await download).saveAs('output/playwright/' + path)
  }
  await page.getByRole('region', { name: 'Холст слайда' }).screenshot({ path: 'output/playwright/illustrated-canvas.png' })
  await page.getByLabel('Открыть JSON', { exact: true }).setInputFiles('output/playwright/illustrated-project.json')
  await page.reload()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  await page.locator('#group').selectOption(generatedGroup)
  check(await page.getByRole('button', { name: 'Иллюстрация', exact: true }).count() === 1, 'Pictures survive JSON import and reload')
  await page.screenshot({ path: 'output/playwright/illustrated-editor.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Editor fits mobile width')
  await page.getByRole('link', { name: 'Диалог', exact: true }).click()
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Generation controls fit mobile width')
  await page.setViewportSize({ width: 1600, height: 1100 })
  return { passed: checks.length, checks }
}
