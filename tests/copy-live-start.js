// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async (page) => {
 await page.setViewportSize({width:1600,height:1100})
 await page.goto('http://localhost:3080/')
 await page.getByRole('heading',{name:'Новая карусель',exact:true}).waitFor()
 await page.getByLabel('Тема *',{exact:true}).fill('Стол, за которым удобно работать')
 await page.getByLabel('Стиль',{exact:true}).fill('Спокойная предметная фотография рабочего стола, естественный свет, тёплые материалы, чистая композиция. В кадре один главный предмет. Без надписей и макетов.')
 await page.getByRole('button',{name:'Задача и аудитория',exact:true}).click()
 await page.getByLabel('Слайдов в серии',{exact:true}).selectOption('4')
 await page.getByLabel('Для кого',{exact:true}).fill('Люди, которые работают дома')
 await page.getByLabel('Цель',{exact:true}).fill('Помочь освободить рабочий стол от лишних вещей')
 await page.getByLabel('Призыв к действию',{exact:true}).fill('Уберите со стола одну лишнюю вещь')
 await page.getByRole('button',{name:/^Чистый/}).click()
 await page.getByRole('button',{name:'Создать проект',exact:true}).click()
 await page.getByRole('link',{name:'Диалог',exact:true}).click()
 await page.getByRole('button',{name:/^Настройки/}).first().click()
 await page.waitForFunction(()=>document.querySelector('#model')?.options.length>2)
 await page.locator('#model').selectOption('openrouter/free')
 await page.locator('#image-model').selectOption('google/gemini-2.5-flash-image')
 await page.getByLabel('Сразу создавать изображения',{exact:true}).uncheck()
 await page.getByRole('button',{name:/^Настройки/}).first().click()
 await page.getByLabel('Запрос',{exact:true}).fill('Создай карусель из четырёх слайдов по брифу.')
 const response=page.waitForResponse(response=>response.url().endsWith('/studio-api/complete')&&response.request().postDataJSON().action==='generate',{timeout:190000})
 await page.getByRole('button',{name:'Отправить запрос',exact:true}).click()
 const result=await (await response).json()
 if(result.error)throw new Error(result.error)
 const proposal=JSON.parse(result.text)
 const download=page.waitForEvent('download')
 await page.evaluate(proposal=>{const url=URL.createObjectURL(new Blob([JSON.stringify(proposal,null,2)],{type:'application/json'})),link=document.createElement('a');link.href=url;link.download='copy-plan.json';link.click();setTimeout(()=>URL.revokeObjectURL(url),1000)},proposal)
 await (await download).saveAs('output/playwright/copy-plan.json')
 return {slides:proposal.slides.map(({title,body})=>({title,body})),model:'openrouter/free',mocked:false}
}
