// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async (page) => {
  const checks = []
  const check = (value, label) => { if (!value) throw new Error(label); checks.push(label) }
  const source = Array.from({ length: 6 }, (_, i) => `**Слайд ${i + 1}**\nНазвание: В поисках смысла жизни ${i + 1}\nТекст: Заметьте, после каких дел вы чувствуете себя живым. Что я сделал сегодня, что меня по-настоящему зарядило? С кем мне легче дышится? Сохраните этот вопрос и вернитесь к нему вечером.\nИзображение: блокнот и чашка чая у окна.\n`).join('\n---\n')
  await page.goto('http://localhost:3080/chat')
  await page.setViewportSize({ width: 1600, height: 1100 })
  await page.frameLocator('iframe').getByRole('textbox', { name: 'Ваше сообщение', exact: true }).waitFor()
  const transfer = async () => {
    const frame = page.frames().find(f => f.url().includes('/legacy/'))
    await frame.evaluate(text => parent.postMessage({ type: 'studio:response', text }, location.origin), source)
    await page.getByLabel('Текст из чата', { exact: true }).waitFor()
  }
  const waitResult = async label => {
    await page.waitForFunction(() => [...document.querySelectorAll('button')].some(b => /Добавить группу|Добавить слайд/.test(b.textContent) && !b.disabled) || [...document.querySelectorAll('[role="alert"]')].some(e => e.getClientRects().length), null, { timeout: 600000 })
    if (await page.getByRole('alert').count()) throw new Error(label + ': ' + await page.getByRole('alert').allTextContents())
  }
  await transfer()
  await page.getByLabel('Запрос', { exact: true }).fill('Преобразуй исходный ответ в группу из ровно 6 слайдов о смысле жизни. Сохрани основные мысли. По 2 коротких предложения на слайд.')
  const request = page.waitForRequest(r => r.url().endsWith('/studio-api/complete'))
  await page.getByRole('button', { name: 'Создать слайды из ответа', exact: true }).click()
  check((await request).postDataJSON().sourceText === source, 'Entire 1687-character response sent without truncation')
  await waitResult('Long answer conversion')
  await page.screenshot({ path: 'output/playwright/prompt-converted.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: 'Добавить группу', exact: true }).click()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  check(await page.getByRole('button', { name: /^Открыть слайд/ }).count() === 6, 'Long Markdown answer becomes six slides')
  const groups = await page.locator('#group option').count()
  await page.getByRole('button', { name: 'Основной текст', exact: true }).click()
  check((await page.getByLabel('Текст слоя', { exact: true }).inputValue()).length > 20, 'Converted content is editable text')
  await page.screenshot({ path: 'output/playwright/prompt-slides.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('link', { name: 'Диалог', exact: true }).click()
  check(await page.getByLabel('Текст из чата', { exact: true }).count() === 0, 'Source cleared only after successful insertion')
  await page.getByLabel('Что создать', { exact: true }).selectOption('slide')
  await page.getByLabel('Запрос', { exact: true }).fill('Создай один слайд о том, как найти смысл в повседневных делах. Один заголовок и два совета.')
  await page.getByRole('button', { name: 'Отправить запрос', exact: true }).click()
  await waitResult('Single slide generation')
  await page.getByRole('button', { name: 'Добавить слайд', exact: true }).click()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  check(await page.getByRole('button', { name: /^Открыть слайд/ }).count() === 7, 'Prompt creates one slide in existing group')
  check(await page.locator('#group option').count() === groups, 'Single slide does not create an extra group')
  await page.getByRole('link', { name: 'Диалог', exact: true }).click()
  await page.getByLabel('Запрос', { exact: true }).fill('Создай новую группу из ровно 3 слайдов о привычке читать книги. По одному короткому совету.')
  await page.getByRole('button', { name: 'Отправить запрос', exact: true }).click()
  await waitResult('Direct group generation')
  await page.getByRole('button', { name: 'Добавить группу', exact: true }).click()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  check(await page.getByRole('button', { name: /^Открыть слайд/ }).count() === 3, 'Prompt directly creates a three-slide group')
  check(await page.locator('#group option').count() === groups + 1, 'Existing groups retained')
  await page.getByRole('link', { name: 'Диалог', exact: true }).click()
  await page.frameLocator('iframe').getByRole('textbox', { name: 'Ваше сообщение', exact: true }).waitFor()
  await transfer()
  await page.route('**/studio-api/complete', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Проверка восстановления после ошибки' }) }))
  await page.getByRole('button', { name: 'Создать слайды из ответа', exact: true }).click()
  await page.getByText('Проверка восстановления после ошибки', { exact: true }).waitFor()
  check(await page.getByLabel('Текст из чата', { exact: true }).inputValue() === source, 'Provider failure preserves complete source')
  check(await page.getByRole('button', { name: 'Создать слайды из ответа', exact: true }).isEnabled(), 'Retry enabled after failure')
  await page.unroute('**/studio-api/complete')
  return { passed: checks.length, checks }
}
