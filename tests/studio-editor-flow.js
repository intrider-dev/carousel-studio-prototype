// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async (page) => {
  const checks = []
  const errors = []
  page.on('pageerror', e => errors.push(e.message))
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label) }
  await page.setViewportSize({ width: 1600, height: 1100 })
  await page.goto('http://localhost:3080')
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  check(await page.locator('#group option').count() >= 3, 'Generated groups persisted after reload')
  await page.getByRole('button', { name: 'Добавить слайд', exact: true }).click()
  await page.getByRole('button', { name: 'Текст', exact: true }).last().click()
  await page.getByLabel('Текст слоя', { exact: true }).fill('Фотография кофе')
  await page.getByLabel('Название слоя', { exact: true }).fill('Заголовок примера')
  await page.getByLabel('Шрифт по умолчанию', { exact: true }).selectOption('Georgia')
  check((await page.locator('#layer-font option').first().innerText()).includes('Georgia'), 'Default font inherited')
  await page.getByLabel('Шрифт слоя', { exact: true }).selectOption('Courier New')
  await page.getByLabel('Размер шрифта', { exact: true }).fill('48')
  await page.getByRole('button', { name: 'Жирный', exact: true }).click()
  await page.getByRole('button', { name: 'Курсив', exact: true }).click()
  await page.getByLabel('Выравнивание', { exact: true }).selectOption('center')
  await page.getByLabel('X', { exact: true }).fill('100')
  await page.getByLabel('Y', { exact: true }).fill('80')
  check(await page.getByLabel('Шрифт слоя', { exact: true }).inputValue() === 'Courier New', 'Element font override')
  await page.getByRole('region', { name: 'Холст слайда' }).focus()
  await page.keyboard.press('Shift+ArrowRight')
  check(await page.getByLabel('X', { exact: true }).inputValue() === '110', 'Keyboard moves selected layer')
  await page.getByRole('button', { name: 'Закрепить', exact: true }).click()
  check(await page.getByLabel('X', { exact: true }).isDisabled(), 'Locked layer blocks editing')
  await page.getByRole('button', { name: 'Открепить', exact: true }).click()
  await page.getByRole('button', { name: 'Скрыть', exact: true }).click()
  check(await page.getByRole('button', { name: 'Показать', exact: true }).isVisible(), 'Hide and show layer')
  await page.getByRole('button', { name: 'Показать', exact: true }).click()
  await page.getByLabel('Добавить фотографии', { exact: true }).setInputFiles(['output/playwright/test-logo.png', 'output/playwright/exported-slide-01.png'])
  await page.getByRole('button', { name: 'Фото', exact: true }).nth(2).waitFor()
  check(await page.getByRole('button', { name: 'Фото', exact: true }).count() === 3, 'Two photos uploaded as separate layers')
  await page.getByLabel('Название слоя', { exact: true }).fill('Фото для проверки')
  await page.getByLabel('Ширина слоя', { exact: true }).fill('400')
  check(await page.getByLabel('Высота слоя', { exact: true }).inputValue() === '500', 'Photo scale preserves aspect ratio')
  await page.getByLabel('X', { exact: true }).fill('180')
  await page.getByLabel('Y', { exact: true }).fill('450')
  await page.getByRole('region', { name: 'Холст слайда' }).scrollIntoViewIfNeeded()
  const box = await page.locator('.konvajs-content').boundingBox()
  const scale = box.width / 1080
  await page.mouse.move(box.x + 260 * scale, box.y + 550 * scale)
  await page.mouse.down()
  await page.mouse.move(box.x + 340 * scale, box.y + 600 * scale, { steps: 10 })
  await page.mouse.up()
  check(Number(await page.getByLabel('X', { exact: true }).inputValue()) > 240, 'Photo drag updates document position')
  const x = Number(await page.getByLabel('X', { exact: true }).inputValue())
  const y = Number(await page.getByLabel('Y', { exact: true }).inputValue())
  await page.getByRole('region', { name: 'Холст слайда' }).scrollIntoViewIfNeeded()
  const b = await page.locator('.konvajs-content').boundingBox()
  await page.mouse.move(b.x + (x + 400) * scale, b.y + (y + 500) * scale)
  await page.mouse.down()
  await page.mouse.move(b.x + (x + 440) * scale, b.y + (y + 550) * scale, { steps: 10 })
  await page.mouse.up()
  check(Number(await page.getByLabel('Ширина слоя', { exact: true }).inputValue()) > 420, 'Corner handle scales photo')
  await page.getByLabel('Поворот', { exact: true }).fill('12')
  await page.getByRole('button', { name: 'Слой назад', exact: true }).click()
  await page.getByRole('button', { name: 'Слой вперёд', exact: true }).click()
  checks.push('Layer order and rotation controls applied')
  await page.getByRole('button', { name: 'Удалить слой', exact: true }).click()
  check(await page.getByRole('button', { name: 'Фото для проверки', exact: true }).count() === 0, 'Photo deletion')
  await page.getByRole('button', { name: 'Отменить изменение', exact: true }).click()
  check(await page.getByRole('button', { name: 'Фото для проверки', exact: true }).count() === 1, 'Undo restores deleted photo')
  await page.getByRole('button', { name: 'Повторить изменение', exact: true }).click()
  check(await page.getByRole('button', { name: 'Фото для проверки', exact: true }).count() === 0, 'Redo repeats deletion')
  const fontsBefore = await page.locator('#default-font option').count()
  await page.getByLabel('Добавить шрифт', { exact: true }).setInputFiles('node_modules/@fontsource-variable/geist/files/geist-cyrillic-wght-normal.woff2')
  await page.waitForFunction(count => document.querySelector('#default-font').options.length === count + 1, fontsBefore)
  const custom = await page.locator('#default-font option').last().getAttribute('value') || await page.locator('#default-font option').last().innerText()
  await page.getByLabel('Шрифт по умолчанию', { exact: true }).selectOption(custom)
  checks.push('Custom WOFF2 uploaded and selected')
  await page.getByRole('button', { name: 'Дублировать слайд', exact: true }).click()
  const count = await page.getByRole('button', { name: /^Открыть слайд/ }).count()
  await page.getByRole('button', { name: 'Удалить слайд', exact: true }).click()
  check(await page.getByRole('button', { name: /^Открыть слайд/ }).count() === count - 1, 'Duplicate and delete slide')
  const save = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Сохранить JSON', exact: true }).click()
  await (await save).saveAs('output/playwright/studio-project.json')
  await page.getByLabel('Открыть JSON', { exact: true }).setInputFiles('package.json')
  check((await page.getByRole('alert').innerText()).includes('повреждён'), 'Invalid project import rejected')
  await page.getByLabel('Открыть JSON', { exact: true }).setInputFiles('output/playwright/studio-project.json')
  await page.waitForFunction(() => !document.querySelector('[role="alert"]'))
  checks.push('Project JSON roundtrip including photos and uploaded font')
  await page.reload()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  check((await page.getByLabel('Шрифт по умолчанию', { exact: true }).inputValue()).includes('geist-cyrillic'), 'Uploaded font persists on reload')
  check(await page.locator('#group option').count() >= 3, 'All groups persist on reload')
  const png = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PNG', exact: true }).click()
  await (await png).saveAs('output/playwright/studio-slide.png')
  const zip = page.waitForEvent('download')
  await page.getByRole('button', { name: 'ZIP группы', exact: true }).click()
  await (await zip).saveAs('output/playwright/studio-slides.zip')
  checks.push('PNG and group ZIP downloaded')
  await page.screenshot({ path: 'output/playwright/studio-editor.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Mobile has no horizontal overflow')
  await page.screenshot({ path: 'output/playwright/studio-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1600, height: 1100 })
  check(errors.length === 0, 'No browser runtime exceptions: ' + errors.join(', '))
  return { passed: checks.length, checks }
}
