// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async (page) => {
  const checks = []
  const check = (ok, label) => { if (!ok) throw new Error(label); checks.push(label) }
  await page.goto('http://localhost:3080/')
  await page.getByRole('heading', { name: 'Новая карусель', exact: true }).waitFor()
  await page.getByLabel('Соотношение сторон').selectOption('16:9')
  check(await page.getByLabel('Высота, px', { exact: true }).inputValue() === '608', 'Landscape preset sets dimensions')
  await page.getByLabel('Соотношение сторон').selectOption('custom')
  await page.getByLabel('Ширина, px', { exact: true }).fill('320')
  await page.getByLabel('Высота, px', { exact: true }).fill('320')
  await page.getByLabel('Тема *', { exact: true }).fill(' ')
  await page.getByRole('button', { name: 'Создать проект', exact: true }).click()
  check((await page.getByRole('alert').innerText()).includes('Укажите тему'), 'Empty topic rejected')
  await page.getByLabel('Тема *', { exact: true }).fill('Предметная фотография кофе')
  await page.getByRole('button', { name: 'Создать проект', exact: true }).click()
  await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).waitFor()
  checks.push('Minimum 320 by 320 format opens correctly')
  await page.getByRole('button', { name: 'Новый проект', exact: true }).click()
  await page.getByRole('button', { name: 'Отмена', exact: true }).click()
  check(await page.getByRole('heading', { name: 'Редактор слайдов', exact: true }).isVisible(), 'Cancel new project preserves current project')
  await page.getByRole('button', { name: 'Новый проект', exact: true }).click()
  await page.getByRole('button', { name: 'Выбрать новый формат', exact: true }).click()
  await page.getByLabel('Соотношение сторон').selectOption('4:5')
  await page.getByLabel('Стиль', { exact: true }).fill('Белый фон, крупные заголовки, фотографии кофе в естественном свете')
  await page.screenshot({ path: 'output/playwright/studio-setup.png', fullPage: true })
  await page.getByRole('button', { name: 'Создать проект', exact: true }).click()
  await page.getByRole('button', { name: 'Заголовок', exact: true }).click()
  await page.getByLabel('Размер шрифта', { exact: true }).fill('300')
  check((await page.getByRole('alert').innerText()).includes('не помещается'), 'Overflow warning shown')
  await page.getByRole('button', { name: 'PNG', exact: true }).click()
  await page.getByText(/Увеличьте высоту слоя/).waitFor()
  checks.push('Export prevents clipped text')
  await page.getByRole('button', { name: 'Подогнать текст', exact: true }).click()
  check(Number(await page.getByLabel('Размер шрифта', { exact: true }).inputValue()) < 300, 'Fit text reduces font to available space')
  const png = page.waitForEvent('download')
  await page.getByRole('button', { name: 'PNG', exact: true }).click()
  await (await png).saveAs('output/playwright/studio-fitted.png')
  checks.push('PNG export succeeds after overflow repair')
  await page.getByLabel('Добавить фотографии', { exact: true }).setInputFiles('package.json')
  await page.getByText(/Фото: PNG, JPEG или WebP/).waitFor()
  checks.push('Unsupported photo file rejected')
  await page.getByRole('tab', { name: 'Создание слайдов', exact: true }).click()
  await page.getByLabel('Действие', { exact: true }).selectOption('analyze')
  await page.getByRole('button', { name: 'Отправить запрос', exact: true }).click()
  await page.getByText('Добавьте изображения чужих слайдов для анализа.', { exact: true }).waitFor()
  checks.push('Analysis requires reference images')
  await page.getByLabel('Действие', { exact: true }).selectOption('generate')
  await page.route('**/studio-api/complete', route => route.fulfill({ status: 502, contentType: 'application/json', body: JSON.stringify({ error: 'Проверка: провайдер временно недоступен.' }) }))
  await page.getByRole('button', { name: 'Отправить запрос', exact: true }).click()
  await page.getByText('Проверка: провайдер временно недоступен.', { exact: true }).waitFor()
  check(await page.locator('#group option').count() === 1, 'Simulated provider failure preserves document')
  await page.unroute('**/studio-api/complete')
  await page.route('**/studio-api/complete', route => route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ text: 'Неверная структура' }) }))
  await page.getByRole('button', { name: 'Отправить запрос', exact: true }).click()
  await page.getByText(/Модель вернула неподходящую структуру/).waitFor()
  check(await page.locator('#group option').count() === 1, 'Simulated malformed response preserves document')
  await page.unroute('**/studio-api/complete')
  return { passed: checks.length, checks }
}
