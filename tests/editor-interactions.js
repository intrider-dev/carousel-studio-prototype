// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async (page) => {
 const checks=[],check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label)}
 await page.getByRole('link',{name:'Редактор',exact:true}).click()
 await page.getByLabel('Открыть JSON',{exact:true}).setInputFiles('output/playwright/verified-project.json')
 await page.locator('#group').selectOption(await page.locator('#group option').last().getAttribute('value'))
 await page.getByRole('tab',{name:'Свойства',exact:true}).click()
 await page.getByRole('button',{name:'Фигура',exact:true}).first().click()
 await page.getByLabel('Название слоя',{exact:true}).fill('Контроль перемещения')
 await page.getByLabel('Тип фигуры',{exact:true}).selectOption('rect')
 const canvas=page.getByRole('region',{name:'Холст слайда',exact:true})
 await canvas.scrollIntoViewIfNeeded()
 const bounds=await canvas.locator('canvas').first().boundingBox()
 const before=Number(await page.getByLabel('X',{exact:true}).inputValue())
 await page.mouse.move(bounds.x+bounds.width*.3,bounds.y+bounds.height*.3)
 await page.mouse.down();await page.mouse.move(bounds.x+bounds.width*.3+45,bounds.y+bounds.height*.3+25,{steps:8});await page.mouse.up()
 check(Number(await page.getByLabel('X',{exact:true}).inputValue())>before,'Drag moves selected layer')
 const moved=Number(await page.getByLabel('X',{exact:true}).inputValue())
 await canvas.focus();await page.keyboard.press('Shift+ArrowRight')
 check(Number(await page.getByLabel('X',{exact:true}).inputValue())===moved+10,'Keyboard moves layer by ten pixels')
 await page.getByRole('button',{name:'Закрепить',exact:true}).click();await canvas.focus();await page.keyboard.press('ArrowRight')
 check(Number(await page.getByLabel('X',{exact:true}).inputValue())===moved+10,'Locked layer cannot move')
 await page.getByRole('button',{name:'Удалить слой',exact:true}).click()
 await page.getByLabel('Добавить фотографии',{exact:true}).setInputFiles(['output/playwright/verified-slide.png','output/playwright/verified-slide.png'])
 await page.waitForFunction(()=>[...document.querySelectorAll('button')].filter(b=>b.textContent==='Фото').length===3)
 check(await page.getByRole('button',{name:'Фото',exact:true}).count()===3,'Multiple uploaded pictures create independent layers')
 await page.getByRole('button',{name:'Удалить слой',exact:true}).click()
 check(await page.getByRole('button',{name:'Фото',exact:true}).count()===2,'Deleting one photo retains the other')
 await page.getByRole('tab',{name:'Бриф и бренд',exact:true}).click()
 await page.getByLabel('Добавить шрифт',{exact:true}).setInputFiles('node_modules/@fontsource-variable/manrope/files/manrope-cyrillic-wght-normal.woff2')
 await page.waitForFunction(()=>document.querySelectorAll('#default-font option').length===13)
 check(await page.locator('#default-font option').count()===13,'Custom font added to built-in catalog')
 await page.waitForFunction(()=>document.querySelector('header [role="status"]')?.textContent==='Сохранено в этом браузере')
 await page.reload();await page.getByRole('heading',{name:'Редактор слайдов',exact:true}).waitFor()
 check(await page.locator('#default-font option').count()===13,'Custom font restored after reload')
 return {passed:checks.length,checks}
}
