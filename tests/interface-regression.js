// oxlint-disable-next-line no-unused-expressions -- Evaluated by the browser CLI.
async(page)=>{
 const checks=[],errors=[],check=(ok,label)=>{if(!ok)throw new Error(label);checks.push(label)}
 page.on('pageerror',e=>errors.push(e.message))
 await page.goto('http://localhost:3080/')
 await page.getByRole('button',{name:'Новый проект',exact:true}).click()
 await page.getByRole('button',{name:'Выбрать новый формат',exact:true}).click()
 await page.getByLabel('Тема *',{exact:true}).fill('Спокойные ежедневные ритуалы')
 await page.getByRole('button',{name:'Создать проект',exact:true}).click()
 await page.getByRole('heading',{name:'Редактор слайдов',exact:true}).waitFor()
 const originalGroupCount=await page.locator('#group option').count()
 await page.getByRole('button',{name:'Свойства',exact:true}).click()
 await page.setViewportSize({width:1600,height:1000})
 check(await page.getByRole('link',{name:'Редактор',exact:true}).getAttribute('aria-current')==='page','Navigation identifies the active page')
 await page.getByRole('button',{name:'Заголовок',exact:true}).click()
 const layerText=await page.getByLabel('Текст слоя',{exact:true}).inputValue()
 const geometry=await page.evaluate(()=>({properties:document.querySelector('.properties-stack [data-slot="card"]:not(.layer-stack)').getBoundingClientRect().top,layers:document.querySelector('.layer-stack').getBoundingClientRect().top,text:document.querySelector('#layer-text').getBoundingClientRect().top,height:innerHeight,order:!!(document.querySelector('#layer-text').compareDocumentPosition(document.querySelector('.layer-stack'))&Node.DOCUMENT_POSITION_FOLLOWING)}))
 check(geometry.properties<geometry.layers&&geometry.text<geometry.height&&geometry.order,'Selected text controls appear before the layer list and fit the viewport')
 await page.getByRole('button',{name:'Бриф и бренд',exact:true}).click()
 check(!await page.getByRole('region',{name:'Холст слайда',exact:true}).isVisible()&&!await page.getByRole('complementary',{name:'Панель редактирования',exact:true}).isVisible(),'Brief opens without unrelated canvas and inspector panels')
 await page.getByRole('button',{name:'Проверка серии',exact:true}).click()
 check(!await page.getByRole('region',{name:'Холст слайда',exact:true}).isVisible(),'Review opens as a focused workspace')
 await page.getByRole('button',{name:'Проверить слайд 1',exact:true}).click()
 check(await page.getByRole('region',{name:'Холст слайда',exact:true}).isVisible(),'Series preview opens the selected slide in the editor')
 await page.getByRole('button',{name:'Заголовок',exact:true}).click()
 check(await page.getByLabel('Текст слоя',{exact:true}).inputValue()===layerText,'Workspace switching preserves selection and text')
 for(const width of [320,390,768,1024,1199,1280,1600]){
  await page.setViewportSize({width,height:1000})
  const bounds=await page.evaluate(()=>({document:document.documentElement.scrollWidth,width:innerWidth,canvas:document.querySelector('[aria-label="Холст слайда"]').getBoundingClientRect(),rail:document.querySelector('.workspace-rail').getBoundingClientRect()}))
  check(bounds.document<=width+1,`Editor has no page overflow at ${width}px`)
  if(width<1024)check(bounds.canvas.top<bounds.rail.top,`Canvas appears before project controls at ${width}px`)
 }
 await page.setViewportSize({width:1600,height:1000})
 await page.waitForFunction(()=>document.querySelector('header [role="status"]')?.textContent==='Сохранено в этом браузере')
 await page.evaluate(()=>window.scrollTo(0,0))
 await page.waitForFunction(()=>document.getAnimations().every(a=>a.playState!=='running'))
 const before=await page.getByRole('region',{name:'Холст слайда',exact:true}).boundingBox()
 await page.getByRole('button',{name:'Проекты',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Проекты',exact:true})
 await dialog.waitFor()
 await page.waitForFunction(()=>document.querySelector('[data-slot="dialog-content"]')?.contains(document.activeElement))
 check((await page.locator('[aria-label="Холст слайда"]').boundingBox()).y===before.y,'Opening the library does not shift the editor')
 await page.keyboard.press('Tab')
 await page.waitForFunction(()=>document.querySelector('[data-slot="dialog-content"]')?.contains(document.activeElement))
 check(await dialog.evaluate(e=>e.contains(document.activeElement)),'Library keeps keyboard focus inside the dialog')
 await page.keyboard.press('Escape');await dialog.waitFor({state:'hidden'})
 await page.waitForFunction(()=>document.activeElement?.id==='project-library-trigger')
 check(await page.getByRole('button',{name:'Проекты',exact:true}).evaluate(e=>e===document.activeElement),'Closing the library restores focus to its trigger')
 await page.getByRole('link',{name:'Диалог',exact:true}).click()
 const clear=page.getByRole('button',{name:'Убрать результат',exact:true})
 if(await clear.count())await clear.click()
 const settings=page.getByRole('button',{name:/^Настройки/}).first()
 await settings.focus();await page.keyboard.press('Enter')
 check(await settings.getAttribute('aria-expanded')==='true','Settings disclosure opens from the keyboard')
 await settings.focus();await page.keyboard.press('Enter')
 check(await settings.getAttribute('aria-expanded')==='false','Settings disclosure closes from the keyboard')
 await page.emulateMedia({reducedMotion:'reduce'})
 await settings.click()
 const reduced=await page.evaluate(()=>({panel:getComputedStyle(document.querySelector('.disclosure-panel')).transitionDuration,spinners:Array.from(document.querySelectorAll('.pending-spinner')).map(e=>getComputedStyle(e).animationName)}))
 check(reduced.panel.split(',').every(v=>parseFloat(v)===0),'Reduced motion removes disclosure movement')
 await page.getByRole('link',{name:'Редактор',exact:true}).click()
 check(await page.evaluate(()=>document.querySelectorAll('[data-motion-region]').length>0&&document.getAnimations().filter(a=>a.playState==='running').length===0),'Reduced motion removes workspace entry movement')
 await page.emulateMedia({reducedMotion:'no-preference'})
 await page.getByRole('link',{name:'Диалог',exact:true}).click()
 for(const width of [320,390,768,1024,1600]){
  await page.setViewportSize({width,height:1000})
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1),`Dialogue has no page overflow at ${width}px`)
 }
 await page.setViewportSize({width:1600,height:1000})
 await settings.click()
 const duration=await page.evaluate(()=>getComputedStyle(document.querySelector('.disclosure-panel')).transitionDuration)
 check(duration.split(',').some(v=>parseFloat(v)>0&&parseFloat(v)<=.2),'Pointer disclosure uses a short transition')
 await settings.click();await settings.click()
 check(await settings.getAttribute('aria-expanded')==='true','Interrupted disclosure returns to the requested open state')
 await page.getByLabel('Поиск модели',{exact:true}).fill('')
 await page.getByLabel('Действие',{exact:true}).selectOption('generate')
 await page.getByLabel('Что создать',{exact:true}).selectOption('group')
 await page.getByLabel('Количество слайдов',{exact:true}).selectOption('1')
 await page.locator('#model').selectOption(await page.locator('#model option').nth(1).getAttribute('value'))
 await page.locator('#image-model').selectOption(await page.locator('#image-model option').nth(1).getAttribute('value'))
 await page.getByLabel('Сразу создавать изображения',{exact:true}).uncheck()
 let releaseImage,imageCalls=0
 const picture=await page.evaluate(()=>{const c=document.createElement('canvas');c.width=1024;c.height=1024;c.getContext('2d').fillStyle='#678b6b';c.getContext('2d').fillRect(0,0,1024,1024);return c.toDataURL('image/png')})
 await page.route('**/studio-api/complete',route=>{
  if(route.request().postDataJSON().action==='image'){imageCalls++;return new Promise(resolve=>{releaseImage=async()=>{await route.fulfill({json:{image:picture}});resolve()}})}
  return route.fulfill({json:{text:JSON.stringify({name:'Проверка переходов',slides:[{title:'Тихий ритуал',body:'Один момент для себя.',layout:'poster',imagePrompt:'Керамика'}]})}})
 })
 await page.getByLabel('Запрос',{exact:true}).fill('Создай один слайд.')
 await page.getByRole('button',{name:'Отправить запрос',exact:true}).click()
 const preview=page.getByLabel('Предпросмотр группы',{exact:true}),picturePreview=preview.locator('img').first()
 await picturePreview.waitFor()
 const frame=await preview.locator('div').first().boundingBox()
 await page.getByRole('button',{name:'Создать изображения',exact:true}).click()
 await page.waitForFunction(()=>document.querySelector('[aria-label="Результат запроса"]')?.getAttribute('aria-busy')==='true')
 check(await picturePreview.isVisible(),'Existing preview stays visible while images are loading')
 const during=await preview.locator('div').first().boundingBox()
 check(Math.abs(during.height-frame.height)<1,'Loading images preserves the preview frame height')
 check(imageCalls===1,'Image creation starts once after explicit approval')
 await releaseImage()
 await page.getByRole('button',{name:'Добавить группу',exact:true}).waitFor()
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('button')).some(b=>b.textContent==='Добавить группу'&&!b.disabled))
 const complete=await preview.locator('div').first().boundingBox()
 check(Math.abs(complete.height-frame.height)<1,'Completed images preserve the preview frame height')
 await page.getByRole('button',{name:'Добавить группу',exact:true}).evaluate(button=>{button.click();button.click()})
 await page.getByRole('heading',{name:'Редактор слайдов',exact:true}).waitFor()
 check(await page.locator('#group option').count()===originalGroupCount+1,'Repeated application creates only one group')
 await page.unroute('**/studio-api/complete')
 await page.getByRole('link',{name:'Редактор',exact:true}).click()
 check(errors.length===0,'No runtime errors during interface navigation')
 return {passed:checks.length,checks}
}
